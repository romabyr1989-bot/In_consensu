-- §8: у архивной таблицы согласий не было первичного ключа.
--
-- consent_archive создавалась через LIKE consent INCLUDING DEFAULTS INCLUDING CONSTRAINTS: копируются
-- умолчания и CHECK, но не первичный ключ — для него нужен INCLUDING INDEXES. Согласие остаётся
-- доказательством и после переноса в архив, а без ключа ничто не мешало положить туда две строки с одним
-- идентификатором. Дубликатов сейчас быть не может (строка удаляется из consent в той же транзакции),
-- поэтому ключ добавляется без предварительной чистки.
ALTER TABLE consent_archive ADD CONSTRAINT consent_archive_pkey PRIMARY KEY (id);

-- FR-4.1: ключ идемпотентности хранится и в квитанции регистрации, и в самом согласии. В квитанции это
-- TEXT, в согласии было VARCHAR(255): ключ длиннее принимался квитанцией и падал при записи согласия —
-- отказ приходился на середину операции. Ширина выравнивается по квитанции.
ALTER TABLE consent ALTER COLUMN idempotency_key TYPE TEXT;

COMMENT ON COLUMN consent.idempotency_key IS
    'Ключ идемпотентности запроса регистрации (FR-4.1); ширина совпадает с registration_receipt';
