-- Этап 8, доработка по сверке с ТЗ (FR-1.5, FR-1.6): текст опубликованной версии фиксируется.
--
-- Раньше в базе лежало только тело с плейсхолдерами, а точный текст собирался заново из настроек
-- оператора и справочника третьих лиц. Стоило изменить реквизиты — и текст версии, по которой уже
-- получены согласия, менялся вместе с ними, а контрольная сумма в досье переставала совпадать.
-- Доказательство обязано быть неизменным, поэтому текст сохраняется в момент публикации.

ALTER TABLE consent_form ADD COLUMN rendered_text TEXT;

COMMENT ON COLUMN consent_form.rendered_text IS 'Точный текст версии на момент публикации; неизменяем (FR-1.5, FR-1.6)';
