-- UI-12: после успешного пробного запуска сотрудник нажимает «Запустить импорт», не загружая файл заново.
-- Содержимое хранится только у пробной задачи и стирается, как только по нему запущен боевой импорт:
-- файл содержит ПДн, и держать его дольше нужного нельзя (§7, NFR-3).
ALTER TABLE import_job ADD COLUMN payload TEXT;

COMMENT ON COLUMN import_job.payload IS
    'Файл пробного запуска до боевого прогона; после запуска стирается (UI-12)';
